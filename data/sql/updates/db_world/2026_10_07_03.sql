-- Adds the tables the zones extractor fills from each zone's spawnData.xml and the game server's spawners read: zone_spawner, one row for each SpawnObject in list order with its name, id, counts, timers, flags, zone levels and its global requirements as the versionable bytes the zone data holds them in, NULL where it has none; and zone_spawner_entry, each SpawnItem a spawner may place, in order, with its chance and the SpawnObjectInfo it places: the class, template, object id, place, facing and scale an object row has, its spawn requirements kept the same way, and the start node type, start node, path and unique location a spawn adds. No row is committed.
CREATE TABLE IF NOT EXISTS `zone_spawner` (
    `zone_path` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `spawner_index` INT UNSIGNED NOT NULL,
    `name` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `spawner_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `active` TINYINT(1) NOT NULL DEFAULT 1,
    `pop_sensitive` TINYINT(1) NOT NULL DEFAULT 0,
    `max_spawns` INT UNSIGNED NOT NULL DEFAULT 0,
    `at_least_one_spawn` TINYINT(1) NOT NULL DEFAULT 0,
    `activate_at_max` TINYINT(1) NOT NULL DEFAULT 0,
    `spawn_time` INT NOT NULL DEFAULT 0,
    `respawn_rate` INT UNSIGNED NOT NULL DEFAULT 0,
    `global_dynamic` TINYINT(1) NOT NULL DEFAULT 0,
    `wait_for_timer` TINYINT(1) NOT NULL DEFAULT 0,
    `zone_level_min` INT UNSIGNED NOT NULL DEFAULT 0,
    `zone_level_max` INT UNSIGNED NOT NULL DEFAULT 0,
    `zone_level_up` INT UNSIGNED NOT NULL DEFAULT 0,
    `global_dynamic_reqs` BLOB NULL,
    PRIMARY KEY (`zone_path`, `spawner_index`),
    KEY `idx_zone_spawner_zone_name` (`zone_path`, `name`),
    CONSTRAINT `fk_zone_spawner_template` FOREIGN KEY (`zone_path`) REFERENCES `zone_template` (`zone_path`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `zone_spawner_entry` (
    `zone_path` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `spawner_index` INT UNSIGNED NOT NULL,
    `position` INT UNSIGNED NOT NULL,
    `percent_chance` TINYINT UNSIGNED NOT NULL DEFAULT 100,
    `class_name` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'class SpawnObjectInfo',
    `template_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `object_id` INT UNSIGNED NOT NULL DEFAULT 0,
    `position_x` FLOAT NOT NULL DEFAULT 0,
    `position_y` FLOAT NOT NULL DEFAULT 0,
    `position_z` FLOAT NOT NULL DEFAULT 0,
    `orientation_x` FLOAT NOT NULL DEFAULT 0,
    `orientation_y` FLOAT NOT NULL DEFAULT 0,
    `orientation_z` FLOAT NOT NULL DEFAULT 0,
    `scale` FLOAT NOT NULL DEFAULT 1,
    `zone_tag` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '',
    `start_state` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '',
    `override_name` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '',
    `global_dynamic` TINYINT(1) NOT NULL DEFAULT 0,
    `undetectable` TINYINT(1) NOT NULL DEFAULT 0,
    `loading_type` TINYINT UNSIGNED NOT NULL DEFAULT 3,
    `spawn_requirements` BLOB NULL,
    `start_node_type` INT NOT NULL DEFAULT 0,
    `start_node` INT UNSIGNED NOT NULL DEFAULT 0,
    `path_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `unique_loc` TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (`zone_path`, `spawner_index`, `position`),
    CONSTRAINT `fk_zone_spawner_entry_spawner` FOREIGN KEY (`zone_path`, `spawner_index`) REFERENCES `zone_spawner` (`zone_path`, `spawner_index`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
